// Tests for generated / co-edit artifact actionability hints.
//
// Two layers: pure-detector unit tests (which path/content shapes emit a hint,
// which do not, evidence/confidence, caps), and integration tests proving the hint
// flows through the Capsule v2 product response, the human/injected-context
// render, the MCP get_context_capsule output schema, and token accounting (counted
// in estimatedOutputTokens, never inflating the naive full-file baseline).
//
// Nothing here pins instance ids or gold-patch data: the astropy-like case is built
// from a seeded grammar file + adjacent generated table, exactly as a real repo
// would carry them.

import assert from "node:assert/strict";
import { mkdtempSync } from "node:fs";
