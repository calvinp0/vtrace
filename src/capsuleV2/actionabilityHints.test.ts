// A PLY-style grammar source body: `def p_*` functions + a yacc reference.
const GRAMMAR_BODY =
  "class CdsFormat:\n"
  + "    \"\"\"CDS unit format parser built on PLY/yacc.\"\"\"\n"
  + "    def parse(self, s):\n"
  + "        return yacc.parse(s)\n"
  + "\n"
  + "def p_division_of_units(p):\n"
  + "    '''\n"
  + "    division_of_units : DIVISION unit_expression\n"
  + "                      | unit_expression DIVISION combined_units\n"
  + "    '''\n"
  + "    p[0] = p[2]";

// A generated parser table body carrying the canonical auto-generated banner.
const PARSETAB_BODY =
  "# cds_parsetab.py\n"
  + "# This file is automatically generated. Do not edit.\n"
  + "_tabversion = '3.10'\n"
  + "_lr_method = 'LALR'";

function grammarFixture(extra: ReadonlyArray<{ relPath: string; specs: ReadonlyArray<{ localName: string; kind: SymbolKind; body: string }> }> = []) {
  return seedCustomFixture([
    {
      relPath: "astropy/units/format/cds.py",
      specs: [
        { localName: "CdsFormat", kind: SymbolKind.Class, body: GRAMMAR_BODY },
      ],
    },
    ...extra,
  ]);
}

// --- (1) grammar source + adjacent *_parsetab.py emits a hint -------------------

test("grammar source with an adjacent _parsetab.py emits a generated_artifact hint", () => {
  const { db, repoRoot } = grammarFixture([
    {
      relPath: "astropy/units/format/cds_parsetab.py",
      specs: [{ localName: "_tabversion", kind: SymbolKind.ModuleVariable, body: PARSETAB_BODY }],
    },
  ]);
  try {
    const hints = detectActionabilityHints({
      db,
      repoRoot,
      candidatePaths: ["astropy/units/format/cds.py"],
    });
    assert.equal(hints.length, 1);
    const hint = hints[0]!;
    assert.equal(hint.kind, "generated_artifact");
    assert.equal(hint.sourceFile, "astropy/units/format/cds.py");
    assert.equal(hint.relatedFile, "astropy/units/format/cds_parsetab.py");
    assert.equal(hint.confidence, "high");
    assert.ok(hint.hint.length > 0);
  } finally {
    db.close();
  }
});

