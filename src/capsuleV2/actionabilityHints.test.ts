// --- (8) MCP get_context_capsule v2 schema documents the hints -----------------

test("get_context_capsule output schema documents capsuleV2.actionabilityHints", () => {
  const tool = RESERVED_MCP_TOOL_DEFINITIONS.find(
    (t) => t.metadata.toolId === McpToolId.GetContextCapsule,
  );
  assert.ok(tool, "get_context_capsule tool definition not found");
  const schema = tool!.metadata.outputSchema as {
    properties?: {
      capsuleV2?: { properties?: Record<string, unknown>; required?: string[] };
    };
  };
  const capsuleV2 = schema.properties?.capsuleV2;
  assert.ok(capsuleV2?.properties?.actionabilityHints, "schema missing actionabilityHints");
  assert.ok(
    capsuleV2?.required?.includes("actionabilityHints"),
    "actionabilityHints not in capsuleV2 required list",
  );
});

// --- (9) run_pipeline / get_code_context preserve hints (carried in capsuleV2) --

test("a run-pipeline-shaped output carries actionabilityHints inside capsuleV2", () => {
  const { db, repoRoot } = grammarFixture([
    {
      relPath: "astropy/units/format/cds_parsetab.py",
      specs: [{ localName: "_tabversion", kind: SymbolKind.ModuleVariable, body: PARSETAB_BODY }],
    },
  ]);
  try {
    const result = buildCapsuleV2({
      db,
      repoRoot,
      task: "CDS format parsing fails when reading a units header.",
      intent: CapsuleIntent.Auto,
      maxTokens: 8_000,
    });
    const product = toCapsuleV2ProductResponse(result);
    // run_pipeline emits the product response verbatim inside `capsuleV2` (a
    // structuredClone). A clone round-trip preserves the field for both
    // run_pipeline and its get_code_context alias.
    const runPipelineOutput = { capsuleV2: structuredClone(product) };
    assert.deepEqual(
      runPipelineOutput.capsuleV2.actionabilityHints,
      product.actionabilityHints,
    );
    assert.ok(runPipelineOutput.capsuleV2.actionabilityHints.length > 0);
  } finally {
    db.close();
  }
});

// --- (10) accounting counts hint text but adds no full-file baseline -----------

test("hint text counts toward estimatedOutputTokens without inflating the naive baseline", async () => {
  const repoRoot = mkdtempSync(path.join(tmpdir(), "vtrace-accounting-"));
  const hint = {
    kind: "generated_artifact" as const,
    sourceFile: "astropy/units/format/cds.py",
    relatedFile: "astropy/units/format/cds_parsetab.py",
    confidence: "high" as const,
    evidence: ["source defines PLY-style grammar functions (def p_*)"],
    hint: "If you change parser/grammar rules here, check whether the generated parser table must be regenerated or updated.",
  };
  const pivots = [{ path: "astropy/units/format/cds.py", source: "x" }];
  const withHints = { capsuleV2: { pivots, support: [], actionabilityHints: [hint] } };
  const withoutHints = { capsuleV2: { pivots, support: [], actionabilityHints: [] } };

  // The hint's relatedFile must NOT enter the file-path groups (no baseline read).
  const groups = runPipelineOutputFilePathGroups(withHints);
  const groupedPaths = groups
    .flat()
    .filter(Boolean)
    .map((bearer) => (bearer as { path?: string }).path);
  assert.ok(
    !groupedPaths.includes("astropy/units/format/cds_parsetab.py"),
    "related artifact must not be added to the naive full-file baseline",
  );

  const noopReader = async () => "";
  const accWith = await buildContextAccounting({
    repoRoot,
    emittedValue: withHints,
    filePathGroups: runPipelineOutputFilePathGroups(withHints),
    latencyMs: 1,
    reader: noopReader,
  });
  const accWithout = await buildContextAccounting({
    repoRoot,
    emittedValue: withoutHints,
    filePathGroups: runPipelineOutputFilePathGroups(withoutHints),
    latencyMs: 1,
    reader: noopReader,
  });
  // Rendered hint text is part of the serialized emitted value → more output tokens.
  assert.ok(
    accWith.estimatedOutputTokens > accWithout.estimatedOutputTokens,
    "hint text should increase estimatedOutputTokens",
  );
  // ...but the naive full-file baseline is identical (no extra file counted).
  assert.equal(
    accWith.estimatedNaiveFullFileTokens,
    accWithout.estimatedNaiveFullFileTokens,
  );
});
