// --- (5) hints are capped at 3 -------------------------------------------------

test("hints are capped at MAX_HINTS (3) even with more grammar/table pairs", () => {
  const extra = [];
  const candidatePaths: string[] = [];
  for (let i = 0; i < 5; i += 1) {
    extra.push({
      relPath: `pkg/g${i}/grammar.py`,
      specs: [{ localName: `Grammar${i}`, kind: SymbolKind.Class, body: GRAMMAR_BODY }],
    });
    extra.push({
      relPath: `pkg/g${i}/grammar_parsetab.py`,
      specs: [{ localName: `_tab${i}`, kind: SymbolKind.ModuleVariable, body: PARSETAB_BODY }],
    });
    candidatePaths.push(`pkg/g${i}/grammar.py`);
  }
  const { db, repoRoot } = seedCustomFixture(extra);
  try {
    const hints = detectActionabilityHints({ db, repoRoot, candidatePaths });
    assert.equal(hints.length, 3);
  } finally {
    db.close();
  }
});

// --- (6) hints reach the Capsule v2 product response (astropy-14369 shape) ------

test("Capsule v2 product response includes the cds.py -> cds_parsetab.py hint", () => {
  const { db, repoRoot } = grammarFixture([
    {
      relPath: "astropy/units/format/cds_parsetab.py",
      specs: [{ localName: "_tabversion", kind: SymbolKind.ModuleVariable, body: PARSETAB_BODY }],
    },
  ]);
  try {
    const result = buildCapsuleV2({
      db,
      repoRoot,
      task: "CDS format parsing fails when reading a units header.",
      intent: CapsuleIntent.Auto,
      maxTokens: 8_000,
    });
    // cds.py is selected (the literal anchor names it), so the detector fires.
    assert.ok(
      result.pivots.some((p) => p.path.includes("cds.py"))
        || result.support.some((s) => s.path.includes("cds.py")),
      "expected cds.py in the capsule selection",
    );
    const internal = result.actionability_hints ?? [];
    assert.ok(
      internal.some(
        (h) => h.sourceFile === "astropy/units/format/cds.py"
          && h.relatedFile === "astropy/units/format/cds_parsetab.py",
      ),
      `expected internal hint, got ${JSON.stringify(internal)}`,
    );
    const product = toCapsuleV2ProductResponse(result);
    assert.ok(Array.isArray(product.actionabilityHints));
    assert.ok(
      product.actionabilityHints.some(
        (h) => h.sourceFile === "astropy/units/format/cds.py"
          && h.relatedFile === "astropy/units/format/cds_parsetab.py",
      ),
      `expected product hint, got ${JSON.stringify(product.actionabilityHints)}`,
    );
    // Always-present field (empty array when none) so consumers can rely on it.
    assert.ok("actionabilityHints" in product);
  } finally {
    db.close();
  }
});

